/*
 * Ending-FMV subtitles (ported from vpsub src/vpsub/fmvsub.S, 9c46426): English subtitles over the ending FMV (archive slot 4864, a 24-bit MDEC movie),
 * composited by the CPU into the frame about to be shown. Hand-written MIPS I (the compiled C version was
 * 1.3 KB; the code and data must fit 932 B).
 *
 * Placement (TECHNICAL "Run-time FMV subtitles"): appended to the FMV player item of pack 4616 (item 3,
 * tag 0x16), which field module 2292 copies to 0x800BEA00 inside a 0x13880-byte heap block. So this runs
 * from 0x800D1DDC, the unused tail of that block; the pack slot's sector slack (934 B) bounds the size.
 *
 * Entry: the player's frame swap (0x800BF664) calls DrawSync(0) after the next frame is decoded. That `jal`
 * (0x800BF68C) is redirected here and its delay slot passes the DISPENV pair (s0) in a0 instead of 0.
 * ``hook`` does the DrawSync. Then, only for movie 0x1300 (the fullscreen loop 0x800BFCE8 keeps its task
 * in s1, slot at +0x34) in 24-bit mode, it draws the page of the current decoded frame (0x800C0C40,
 * 1..537 at 15 fps) into env[idx ^ 1], the buffer the swap shows next (idx = 0x800C0C4C, the one on
 * screen). The next decode overwrites that buffer whole.
 *
 * Drawing (stack frame 5136 B, within the never-used 0x801FDD00-0x801FF300 below the stack):
 *  - A colour map of 14 rows x 300 px (screen x 10..309, rows BOTTOM-1 .. BOTTOM+12) is built from
 *    the glyph strip.
 *    - An ink pixel stores 248 (white).
 *    - Its 4 neighbours get OR 16 (dark outline; 248 | 16 = 248, so ink is kept).
 *  - Per row:
 *    - StoreImage reads the 450-halfword (300 px, 24-bit) VRAM row.
 *    - Every non-zero map byte replaces that pixel's R, G and B.
 *    - LoadImage writes the row back.
 *
 * Data (fmvdata.inc, generated by src/vpundub/subtitles/fmvsub.py):
 *  - WT: width of the glyph strip.
 *  - cols[ng + 1]: first strip column of each glyph; width = next entry minus this one.
 *  - bits: the strip, 12 rows of WT bits, MSB first.
 *  - pages, halfword aligned: u16 start, u16 end (decoded frames, shown while start <= f < end), u8 n,
 *    u8 x (map column of the line), u8 glyph[n], pad to even. Ends at start = 0.
 *  - A 1 px gap between touching glyphs is a blank glyph.
 */
    .set noreorder
    .set noat

    .include "fmvdata.inc"

    .equ COLX, 10              /* screen x of map column 0 */
    .equ MW, 300               /* map width, px */
    .equ RECT, 16              /* stack: 16 B arg area, RECT, row buffer, map, saved regs */
    .equ ROWB, RECT + 8
    .equ MAP, ROWB + 3 * MW
    .equ SAV, MAP + 14 * MW
    .equ FS, SAV + 16
    .equ BOTTOM, 209           /* top ink row of the line (pages.BOTTOM) */
    .equ INK, 248
    .equ DARK, 16

    .section .text.hook,"ax",@progbits
    .globl hook
hook:
    addiu   $sp, $sp, -FS
    sw      $ra, SAV($sp)
    sw      $s0, SAV+4($sp)
    sw      $s4, SAV+8($sp)
    move    $s0, $a0
    jal     DrawSync                /* the call this hook replaces */
    move    $a0, $zero
    lw      $t0, 0x34($s1)          /* movie task: archive slot of the STR */
    lbu     $t2, 0x11($s0)          /* env[0].isrgb24 */
    li      $t1, 0x1300
    bne     $t0, $t1, out
    lui     $t3, 0x800C
    beqz    $t2, out
    lw      $t4, 0x0C4C($t3)        /* buffer on screen */
    lw      $t5, 0x0C40($t3)        /* decoded frames */
    xori    $t4, $t4, 1
    sll     $t6, $t4, 2
    sll     $t4, $t4, 4
    addu    $t4, $t4, $t6
    addu    $s0, $s0, $t4           /* &env[idx ^ 1].disp */
    lui     $t9, 0x800D             /* %hi of every data label (fmvsub.compile checks) */
    addiu   $t8, $t9, %lo(pages)
page:
    lhu     $t2, 0($t8)             /* start */
    lhu     $t3, 2($t8)             /* end */
    lbu     $t7, 4($t8)             /* n */
    beqz    $t2, out
    sltu    $t2, $t5, $t2           /* f < start */
    bnez    $t2, next
    sltu    $t3, $t5, $t3           /* f < end */
    bnez    $t3, found
    lbu     $t6, 5($t8)             /* x: map column of the pen */
next:
    addiu   $t8, $t8, 7
    addu    $t8, $t8, $t7
    srl     $t8, $t8, 1
    b       page
    sll     $t8, $t8, 1

found:
    addiu   $t0, $sp, MAP           /* clear the map */
    addiu   $t1, $sp, SAV
1:  addiu   $t0, $t0, 4
    bne     $t0, $t1, 1b
    sw      $zero, -4($t0)
    addiu   $t8, $t8, 6
    li      $t1, INK
char:
    beqz    $t7, blend
    addiu   $t7, $t7, -1
    lbu     $t0, 0($t8)
    addiu   $t8, $t8, 1
    addu    $t0, $t0, $t9
    lbu     $t2, %lo(cols)($t0)     /* strip column = bit index in row 0 */
    lbu     $t3, %lo(cols+1)($t0)
    addiu   $a0, $sp, MAP + MW      /* map row 1 = glyph row 0 */
    addu    $a0, $a0, $t6
    subu    $t3, $t3, $t2           /* glyph width */
    li      $a1, 12
2:  addu    $a2, $a0, $t3           /* row: a0 .. a2 */
    move    $v0, $a0
3:  srl     $t4, $t2, 3
    addu    $t4, $t4, $t9
    lbu     $t4, %lo(bits)($t4)
    andi    $t5, $t2, 7
    sllv    $t4, $t4, $t5
    andi    $t4, $t4, 0x80
    beqz    $t4, 4f
    addiu   $t2, $t2, 1
    lbu     $v1, -1($v0)            /* ink: outline around, ink on top */
    lbu     $at, 1($v0)
    ori     $v1, $v1, DARK
    sb      $v1, -1($v0)
    ori     $at, $at, DARK
    sb      $at, 1($v0)
    lbu     $v1, -MW($v0)
    lbu     $at, MW($v0)
    ori     $v1, $v1, DARK
    sb      $v1, -MW($v0)
    ori     $at, $at, DARK
    sb      $at, MW($v0)
    sb      $t1, 0($v0)
4:  addiu   $v0, $v0, 1
    bne     $v0, $a2, 3b
    nop
    addiu   $t2, $t2, WT            /* next strip row */
    subu    $t2, $t2, $t3
    addiu   $a1, $a1, -1
    bnez    $a1, 2b
    addiu   $a0, $a0, MW
    b       char
    addu    $t6, $t6, $t3

blend:
    lhu     $t0, 0($s0)             /* disp.x, disp.y */
    lhu     $t1, 2($s0)
    lui     $t2, 1                  /* h 1 */
    ori     $t2, $t2, 3 * MW / 2    /* w 450 halfwords */
    addiu   $t0, $t0, 3 * COLX / 2
    sh      $t0, RECT($sp)
    addiu   $t1, $t1, BOTTOM - 1
    sh      $t1, RECT+2($sp)
    sw      $t2, RECT+4($sp)
    addiu   $s4, $sp, MAP
5:  addiu   $a0, $sp, RECT
    jal     StoreImage
    addiu   $a1, $sp, ROWB
    jal     DrawSync
    move    $a0, $zero
    addiu   $t0, $sp, ROWB
    addiu   $t1, $s4, MW
6:  lbu     $t3, 0($s4)
    addiu   $s4, $s4, 1
    beqz    $t3, 7f
    addiu   $t0, $t0, 3
    sb      $t3, -3($t0)
    sb      $t3, -2($t0)
    sb      $t3, -1($t0)
7:  bne     $s4, $t1, 6b
    nop
    addiu   $a0, $sp, RECT
    jal     LoadImage
    addiu   $a1, $sp, ROWB
    jal     DrawSync
    move    $a0, $zero
    lhu     $t0, RECT+2($sp)
    addiu   $t1, $sp, SAV
    addiu   $t0, $t0, 1
    bne     $s4, $t1, 5b
    sh      $t0, RECT+2($sp)
out:
    lw      $ra, SAV($sp)
    lw      $s0, SAV+4($sp)
    lw      $s4, SAV+8($sp)
    jr      $ra
    addiu   $sp, $sp, FS
