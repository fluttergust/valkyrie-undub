#!/usr/bin/env python3
"""VALKYRIE.BIN header/TOC codec (Valkyrie Profile USA, SLUS-01156/01179).

The archive (disc LBA 150) starts with a 25,600-byte header (13 sectors, the rest of sector 12 unused):

  bytes 0     .. 20479   5120 little-endian words: word 0 = magic 0x19563824, words 1..5119 = file entries
  bytes 20480 .. 25599   5120 bytes: low byte of each file's size in sectors (byte i belongs to word i)

Entry word i (as bytes): b0 = minutes, b1 = seconds, b2 = frames (BCD, absolute disc MSF, LBA = MSF - 150),
b3 = high byte of the size in sectors. size_sectors = b3 << 8 | sizes[i]. Size 0 = file not on this disc.

Encryption (loader routine at 0x80011DD0): a generator seeded with 0x64283921 runs 5120 steps. Step i XORs word i
with k, then k2 = k ^ (k << 1) XORs size byte i with (k2 & 0xFF), then k = ~k2 ^ 0x64283921.
The game checks the magic (0x80011E50) and reads sizes via 0x80011CA0: bytes = (b3 << 8 | sizes[i]) << 11.
"""
from __future__ import annotations

import struct
import sys
from dataclasses import dataclass

SECTOR_RAW = 2352
USER_OFF = 24
USER_SIZE = 2048
ARCHIVE_LBA = 150
HEADER_SECTORS = 13
N_WORDS = 5120
TOC_BYTES = N_WORDS * 4            # 20480
SIZES_BYTES = N_WORDS              # 5120
HEADER_BYTES = TOC_BYTES + SIZES_BYTES
MAGIC = 0x19563824
SEED = 0x64283921


def read_user(path: str, lba: int, count: int = 1) -> bytes:
    out = bytearray()
    with open(path, "rb") as f:
        for i in range(count):
            f.seek((lba + i) * SECTOR_RAW + USER_OFF)
            out += f.read(USER_SIZE)
    return bytes(out)


def read_header(path: str) -> bytes:
    """Return the raw (encrypted) 25600-byte archive header from a disc image."""
    return read_user(path, ARCHIVE_LBA, HEADER_SECTORS)[:HEADER_BYTES]


def keystream() -> bytes:
    """HEADER_BYTES of keystream (word keys then byte keys), as generated by the loader."""
    k = SEED
    wk = bytearray()
    bk = bytearray()
    for _ in range(N_WORDS):
        wk += struct.pack("<I", k)
        k2 = (k ^ (k << 1)) & 0xFFFFFFFF
        bk.append(k2 & 0xFF)
        k = (~k2 ^ SEED) & 0xFFFFFFFF
    return bytes(wk + bk)


KEYSTREAM = keystream()


def crypt(header: bytes) -> bytes:
    """XOR the header with the keystream. The same call encrypts and decrypts."""
    assert len(header) == HEADER_BYTES
    return bytes(a ^ b for a, b in zip(header, KEYSTREAM))


def bcd(x: int) -> int:
    return (x >> 4) * 10 + (x & 15)


def to_bcd(v: int) -> int:
    if not 0 <= v < 100:
        raise ValueError(v)
    return (v // 10) << 4 | (v % 10)


def msf_to_lba(m: int, s: int, f: int) -> int:
    return (m * 60 + s) * 75 + f - 150


def lba_to_msf(lba: int) -> tuple[int, int, int]:
    a = lba + 150
    return a // 4500, (a // 75) % 60, a % 75


@dataclass(frozen=True)
class Entry:
    index: int
    lba: int | None      # absolute disc LBA, None if absent on this disc
    size: int            # size in sectors (0 if absent)

    def encode(self) -> tuple[bytes, int]:
        """Return (4-byte word, size low byte)."""
        if self.lba is None:
            assert self.size == 0
            return bytes(4), 0
        assert 0 < self.size < 0x10000
        m, s, f = lba_to_msf(self.lba)
        return bytes((to_bcd(m), to_bcd(s), to_bcd(f), self.size >> 8)), self.size & 0xFF


def decode_entry(index: int, word: bytes, size_lo: int) -> Entry:
    size = word[3] << 8 | size_lo
    if word[:3] == b"\0\0\0":
        if size:
            raise ValueError(f"entry {index}: zero MSF with size {size}")
        return Entry(index, None, 0)
    if not size:
        raise ValueError(f"entry {index}: MSF without size")
    return Entry(index, msf_to_lba(bcd(word[0]), bcd(word[1]), bcd(word[2])), size)


@dataclass
class Toc:
    entries: list[Entry]     # entries[i].index == i + 1
    pad: int = 0             # size byte 0 (belongs to the magic word; 0 on retail discs)

    @classmethod
    def parse(cls, plain: bytes) -> "Toc":
        if struct.unpack_from("<I", plain, 0)[0] != MAGIC:
            raise ValueError("bad TOC magic")
        sizes = plain[TOC_BYTES:HEADER_BYTES]
        ents = [decode_entry(i, plain[i * 4:i * 4 + 4], sizes[i]) for i in range(1, N_WORDS)]
        return cls(ents, sizes[0])

    def build(self) -> bytes:
        words = bytearray(struct.pack("<I", MAGIC))
        sizes = bytearray([self.pad])
        for i, e in enumerate(self.entries, 1):
            assert e.index == i
            w, lo = e.encode()
            words += w
            sizes.append(lo)
        return bytes(words + sizes)

    def get(self, index: int) -> Entry:
        return self.entries[index - 1]

    def extents(self, end_lba: int) -> dict[int, tuple[int, int]]:
        """index -> (lba, sectors up to the next higher start LBA or end_lba). Includes inter-file padding."""
        starts = sorted({e.lba for e in self.entries if e.lba is not None} | {end_lba})
        nxt = {a: b for a, b in zip(starts, starts[1:])}
        return {e.index: (e.lba, nxt[e.lba] - e.lba) for e in self.entries if e.lba is not None}


def load(path: str) -> tuple[Toc, bytes]:
    """Return (toc, ciphertext) for a disc image."""
    c = read_header(path)
    return Toc.parse(crypt(c)), c


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: vptoc.py <disc.bin>", file=sys.stderr)
        return 2
    toc, c = load(argv[1])
    assert crypt(toc.build()) == c, "round-trip failed"
    present = [e for e in toc.entries if e.lba is not None]
    print(f"entries present {len(present)}/{len(toc.entries)}")
    for e in present:
        print(f"{e.index:5d} lba {e.lba:7d} sectors {e.size:6d}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
